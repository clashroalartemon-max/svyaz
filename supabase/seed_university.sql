-- Реальное руководство: начальник университета — Калиниченко Игорь
-- Александрович, генерал-лейтенант полиции (официальный сайт университета).
do $$
declare
  v_id uuid;
  v_login text;
  v_hash text;
begin
  select p.id into v_id
    from public.profiles p
   where lower(regexp_replace(p.full_name, '\s+', ' ', 'g'))
         = lower('Калиниченко Игорь Александрович')
   limit 1;

  if v_id is null then
    v_login := 'kalinichenko';
    v_id := gen_random_uuid();
    insert into public.profiles
      (id, login, full_name, group_name, role, military_rank, position, role_level, department, phone)
    values
      (v_id, v_login, 'Калиниченко Игорь Александрович', '', 'cadet',
       'генерал-лейтенант', 'Начальник университета', 10, 'Руководство университета', null);
    v_hash := encode(sha256(convert_to(v_login || ':test1234', 'UTF8')), 'hex');
    insert into public.credentials (profile_id, password_hash)
      values (v_id, v_hash)
      on conflict (profile_id) do update set password_hash = excluded.password_hash;
  else
    update public.profiles
       set military_rank = 'генерал-лейтенант',
           position = 'Начальник университета',
           department = 'Руководство университета',
           role_level = 10
     where id = v_id;
  end if;
end $$;

